import assert from 'node:assert/strict';
import { CalculatorService } from '../src/modules/keyboard-builder/services/calculator.service';
import { CheckoutService } from '../src/modules/checkout/services/checkout.service';
import { KEYBOARD_OPTIONS } from '../src/modules/keyboard-builder/models/keyboard-options';
import { keyboardGeometry } from '../src/modules/keyboard-builder/components/keyboard-interactive-engine/keyboard-geometry';
import { keyColorId } from '../src/modules/keyboard-builder/components/keyboard-interactive-engine/key-colors';
import type { KeyboardDesign } from '../src/modules/keyboard-builder/models/keyboard.types';

const calculator = new CalculatorService();
const design: KeyboardDesign = structuredClone(KEYBOARD_OPTIONS.initial);
assert.equal(calculator.calculate(design).totalCents, 13000);
assert.equal(calculator.calculate({ ...design, size: '60' }).totalCents, 8000);
assert.equal(calculator.calculate({ ...design, physical: 'iso', languages: ['en', 'he'], presetId: 'custom', customColorMode: 3 }).totalCents, 16500);
const key = keyboardGeometry(design).keys[0]!;
design.keyColors = { [keyColorId(design, key)]: '#112233', 'inactive-key': '#445566' };
assert.equal(calculator.calculate(design).totalCents, 13150);
assert.equal(calculator.calculate({ ...design, size: '60' }).totalCents, 8000);
const checkout = new CheckoutService();
checkout.addConfiguration(design);
const id = checkout.basket.get()[0]!.id;
design.customColors.letters = '#000000';
design.languages = ['he'];
assert.notEqual(checkout.basket.get()[0]!.design.customColors.letters, '#000000');
assert.deepEqual(checkout.basket.get()[0]!.design.languages, ['en']);
checkout.setQuantity(id, 3);
assert.equal(checkout.totalCents(), 39450);
for (const invalid of [0, -1, 1.5, NaN, 100]) checkout.setQuantity(id, invalid);
assert.equal(checkout.basket.get()[0]!.quantity, 3);
checkout.remove(id);
assert.equal(checkout.totalCents(), 0);
assert.equal(checkout.basket.get().length, 0);
console.log('PASS: pricing adjustments, active keys, basket snapshots, quantities, and removal');
