import { KeyboardDesignService } from '../src/modules/keyboard-builder/services/keyboard-design.service';
import { keyboardGeometry, hitKeyboardKey } from '../src/modules/keyboard-builder/components/keyboard-interactive-engine/keyboard-geometry';
import { keyColor, keyColorId, legendColor } from '../src/modules/keyboard-builder/components/keyboard-interactive-engine/key-colors';
const service = new KeyboardDesignService();
const assert = (condition: boolean, message: string) => { if (!condition) throw new Error(message); };
assert(!service.toggleLanguage('en'), 'One language must remain');
assert(service.toggleLanguage('he'), 'Second language accepted');
assert(!service.toggleLanguage('ar'), 'Third language rejected');
assert(service.design.get().languages.join() === 'en,he', 'Rejected language does not change state');
service.setCorner('top-right');
service.swapLanguages();
assert(service.design.get().languages.join() === 'he,en', 'Swap order');
assert(service.design.get().primaryCorner === 'top-right', 'Swap preserves chosen corner');
service.setSize('60'); service.setPhysical('iso'); service.setLetterLayout('azerty');
assert(service.design.get().languages.join() === 'he,en', 'Other choices preserve languages');
assert(service.toggleLanguage('en'), 'Remove one language');
assert(service.toggleLanguage('ar'), 'Replace removed language');
assert(service.design.get().languages.join() === 'he,ar', 'Replacement order');
service.setSize('100'); service.setPhysical('ansi'); service.setPreset('navy-coral');
let design = service.design.get();
const keys = keyboardGeometry(design).keys;
const letter = keys.find(key => key.row === 0 && key.letter === 0)!;
const enter = keys.find(key => key.label === 'Enter')!;
const f5 = keys.find(key => key.label === 'F5')!;
const f8 = keys.find(key => key.label === 'F8')!;
const f9 = keys.find(key => key.label === 'F9')!;
assert(keyColor(design, f5) === keyColor(design, f8), 'F5–F8 accent group');
assert(keyColor(design, f5) !== keyColor(design, f9), 'F9 outside accent group');
assert(keyColor(design, enter) !== keyColor(design, letter), 'Action and letter groups differ');
const id = keyColorId(design, letter);
service.selectKey(id); service.setKeyColor('#ff0000');
assert(keyColor(service.design.get(), letter) === '#ff0000', 'Individual override');
service.setPreset('graphite');
assert(keyColor(service.design.get(), letter) === '#ff0000', 'Preset preserves override');
service.resetKeyColor();
design = service.design.get();
assert(keyColor(design, letter) === keyColor(design, enter), 'Monochrome after reset');
assert(legendColor('#000000') === '#ffffff' && legendColor('#ffffff') === '#111111', 'Readable legend colors');
assert(hitKeyboardKey(keys, { x: letter.x + 0.6, y: letter.y + 0.6 }) === letter, 'Hit test key center');
assert(hitKeyboardKey(keys, { x: -100, y: -100 }) === undefined, 'Miss outside keyboard');
service.setKeyColor('#ff0000'); service.resetAllColors();
assert(Object.keys(service.design.get().keyColors).length === 0, 'Clear all overrides');
document.querySelector('#results')!.textContent = 'PASS: language constraints, independent settings, presets, F5–F8, per-key colors, resets, contrast and hit testing';
